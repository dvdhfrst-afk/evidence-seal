"""A seal made on one system must check out on another.

The golden files were written once and are never regenerated by the tests. The same
folder must seal to those exact bytes on every system, which is what makes a token
made on one system valid on another.
"""

import json
import os
import shutil
import unicodedata
import unittest
from pathlib import Path

from tests.support import FIXTURES, TempFolderTestCase, run_cli

PORTABLE = FIXTURES / "portable"
ROOT = PORTABLE / "test-authority-root.crt"
RECIPE = (
    ("unix-endings.txt", b"line one\nline two\n"),
    ("windows-endings.txt", b"line one\r\nline two\r\n"),
    ("old-mac-endings.txt", b"line one\rline two\r"),
    ("no-final-newline.txt", b"no newline at the end"),
    ("empty.txt", b""),
    ("binary.bin", bytes(range(256))),
    ("name with spaces.txt", b"spaces\n"),
    ("Upper-Case.TXT", b"case is kept\n"),
    ("caf\u00e9.txt", b"one precomposed character\n"),
    ("\u6f22\u5b57/\U0001f600.txt", b"other scripts\n"),
    ("a-b", b"sort order, a hyphen sorts before a slash\n"),
    ("a/b", b"sort order, nested\n"),
    ("a_b", b"sort order, an underscore sorts after a slash\n"),
    ("Z.txt", b"sort order, upper case first\n"),
    ("deep/deeper/deepest/file.txt", b"nested\n"),
)
FOLDER_NAME = "portable-work"


def build(parent):
    folder = Path(parent) / FOLDER_NAME
    for relative, data in RECIPE:
        path = folder / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    return folder


class Golden(TempFolderTestCase):
    def test_the_same_folder_seals_to_the_same_bytes_on_every_system(self):
        folder = build(self.temp)
        out = self.temp / "made-here.txt"
        code, _, err = run_cli("seal", folder, "--purpose", "Portable test", "--date", "2026-11-07", "--out", out)
        self.assertEqual(code, 0, err)
        self.assertEqual(out.read_bytes(), (PORTABLE / "golden-manifest.txt").read_bytes())

    def test_a_token_made_elsewhere_verifies_here(self):
        build(self.temp)
        for suffix in ("golden-manifest.txt", "golden-manifest.tsr"):
            shutil.copyfile(PORTABLE / suffix, self.temp / suffix)
        code, out, err = run_cli("verify", self.temp / "golden-manifest.txt", "--folder", self.temp / FOLDER_NAME, "--ca", ROOT)
        self.assertEqual(code, 0, out + err)

    def test_converting_line_endings_is_noticed(self):
        folder = build(self.temp)
        shutil.copyfile(PORTABLE / "golden-manifest.txt", self.temp / "m.txt")
        path = folder / "unix-endings.txt"
        path.write_bytes(path.read_bytes().replace(b"\n", b"\r\n"))
        code, text, _ = run_cli("verify", self.temp / "m.txt", "--folder", folder, "--json")
        self.assertEqual(code, 1)
        self.assertEqual(json.loads(text)["differences"]["changed"], ["unix-endings.txt"])

    def test_a_manifest_with_converted_line_endings_is_noticed(self):
        folder = build(self.temp)
        data = (PORTABLE / "golden-manifest.txt").read_bytes().replace(b"\n", b"\r\n")
        path = self.write("m.txt", data)
        shutil.copyfile(PORTABLE / "golden-manifest.tsr", self.temp / "m.tsr")
        code, text, _ = run_cli("verify", path, "--folder", folder, "--ca", ROOT, "--json")
        data = json.loads(text)
        self.assertEqual(code, 1)
        self.assertEqual(data["files"]["status"], "fail")
        self.assertIn("line feeds", data["files"]["detail"])
        hash_check = next(check for check in data["token_checks"] if check["key"] == "hash")
        self.assertEqual(hash_check["status"], "fail")


def same_name_survives(folder, name):
    return name in os.listdir(folder)


class UnicodeForms(TempFolderTestCase):
    def setUp(self):
        super().setUp()
        self.composed = unicodedata.normalize("NFC", "caf\u00e9.txt")
        self.decomposed = unicodedata.normalize("NFD", "caf\u00e9.txt")

    def seal_as(self, name, folder_name="work"):
        folder = self.temp / folder_name
        folder.mkdir(exist_ok=True)
        (folder / name).write_bytes(b"coffee\n")
        out = self.temp / "m.txt"
        code, _, err = run_cli("seal", folder, "--purpose", "p", "--out", out, "--force")
        self.assertEqual(code, 0, err)
        return folder, out

    def rename(self, folder, old, new):
        os.rename(folder / old, folder / new)
        if not same_name_survives(folder, new):
            self.skipTest("this file system stores only one Unicode form of a name")

    def test_either_form_on_disk_matches_either_form_in_the_manifest(self):
        for first, second in ((self.composed, self.decomposed), (self.decomposed, self.composed)):
            with self.subTest(first=ascii(first)):
                folder, out = self.seal_as(first)
                self.rename(folder, first, second)
                _, text, _ = run_cli("verify", out, "--folder", folder, "--json")
                data = json.loads(text)
                self.assertEqual(data["files"]["status"], "pass", text)
                self.assertEqual(data["differences"]["added"], [])
                self.assertEqual(data["differences"]["matched_under_another_unicode_form"], {first: second})
                self.assertTrue(any("another Unicode form" in note for note in data["notes"]))
                shutil.rmtree(folder)

    def test_changed_content_under_another_form_is_still_a_change(self):
        folder, out = self.seal_as(self.composed)
        self.rename(folder, self.composed, self.decomposed)
        (folder / self.decomposed).write_bytes(b"tea\n")
        code, text, _ = run_cli("verify", out, "--folder", folder, "--json")
        self.assertEqual(code, 1)
        self.assertEqual(json.loads(text)["differences"]["changed"], [self.composed])

    def test_a_second_file_in_the_other_form_is_an_added_file(self):
        folder, out = self.seal_as(self.composed)
        (folder / self.decomposed).write_bytes(b"different file\n")
        if not same_name_survives(folder, self.composed) or len(os.listdir(folder)) != 2:
            self.skipTest("this file system stores only one Unicode form of a name")
        code, text, _ = run_cli("verify", out, "--folder", folder, "--json")
        self.assertEqual(code, 1)
        self.assertEqual(json.loads(text)["differences"]["added"], [self.decomposed])

    def test_exclude_patterns_match_either_form(self):
        folder, _ = self.seal_as(self.decomposed)
        (folder / "keep.txt").write_bytes(b"k\n")
        out = self.temp / "n.txt"
        code, _, err = run_cli("seal", folder, "--purpose", "p", "--out", out, "--exclude", self.composed)
        self.assertEqual(code, 0, err)
        data = out.read_bytes()
        self.assertIn(b"keep.txt", data)
        self.assertNotIn("  " + self.decomposed, data.decode("utf-8"))

    def test_the_folder_is_found_under_either_form(self):
        name = unicodedata.normalize("NFC", "d\u00e9j\u00e0")
        folder, out = self.seal_as("a.txt", name)
        other = self.temp / unicodedata.normalize("NFD", name)
        os.rename(folder, other)
        if not same_name_survives(self.temp, other.name):
            self.skipTest("this file system stores only one Unicode form of a name")
        _, text, _ = run_cli("verify", out, "--json")
        self.assertEqual(json.loads(text)["files"]["status"], "pass", text)


class CaseAndSeparators(TempFolderTestCase):
    def test_a_case_only_rename_is_a_change_with_a_pointer(self):
        folder = self.write("work/Report.TXT", b"r\n").parent
        out = self.temp / "m.txt"
        self.assertEqual(run_cli("seal", folder, "--purpose", "p", "--out", out)[0], 0)
        os.rename(folder / "Report.TXT", folder / "report.txt")
        code, text, _ = run_cli("verify", out, "--folder", folder, "--json")
        data = json.loads(text)
        self.assertEqual(code, 1)
        self.assertEqual(data["differences"]["missing"], ["Report.TXT"])
        self.assertEqual(data["differences"]["possible_moves"], {"Report.TXT": "report.txt"})

    def test_two_names_differing_only_in_case_from_another_system(self):
        folder = self.write("work/a.txt", b"lower\n").parent
        lines = [
            "evidence-seal manifest v1",
            "purpose: p",
            "created: 2026-11-07",
            "folder: work",
            "algorithm: sha256",
            "files: 2",
            "total-bytes: 12",
            "",
            "0" * 64 + "  6  A.txt",
            "0" * 64 + "  6  a.txt",
        ]
        path = self.write("m.txt", ("\n".join(lines) + "\n").encode())
        code, text, _ = run_cli("verify", path, "--folder", folder, "--json")
        self.assertEqual(code, 1, text)

    def test_windows_separators_in_a_hand_made_list(self):
        import hashlib

        folder = self.write("work/sub/dir/a.txt", b"a\n").parent.parent.parent
        digest = hashlib.sha256(b"a\n").hexdigest()
        path = self.write("work/hand.txt", f"{digest}  sub\\dir\\a.txt\r\n{digest} *./sub/dir/a.txt\r\n".encode())
        _, text, _ = run_cli("verify", path, "--folder", folder, "--allow-added", "--json")
        data = json.loads(text)
        self.assertEqual(data["files"]["status"], "pass", text)
        self.assertEqual(data["differences"]["unchanged"], 1)

    def test_manifest_lines_never_use_a_backslash_as_a_separator(self):
        folder = self.write("work/sub/a.txt", b"a\n").parent.parent
        out = self.temp / "m.txt"
        self.assertEqual(run_cli("seal", folder, "--purpose", "p", "--out", out)[0], 0)
        self.assertIn(b"  sub/a.txt\n", out.read_bytes())


@unittest.skipUnless(os.name == "nt", "Windows paths")
class WindowsPaths(TempFolderTestCase):
    def long(self, path):
        return "\\\\?\\" + os.path.abspath(str(path))

    def cleanup(self, path):
        shutil.rmtree(self.long(path), ignore_errors=True)

    def test_paths_over_the_old_260_character_limit(self):
        folder = self.temp / "long"
        deep = folder
        for index in range(12):
            deep = deep / ("segment-of-thirty-characters-" + str(index % 10))
        self.addCleanup(self.cleanup, folder)
        os.makedirs(self.long(deep))
        name = self.long(deep / "file.txt")
        with open(name, "wb") as stream:
            stream.write(b"deep\n")
        self.assertGreater(len(name), 300)
        out = self.temp / "m.txt"
        code, _, err = run_cli("seal", folder, "--purpose", "p", "--out", out)
        self.assertEqual(code, 0, err)
        self.assertIn(b"file.txt\n", out.read_bytes())
        _, text, _ = run_cli("verify", out, "--folder", folder, "--json")
        self.assertEqual(json.loads(text)["files"]["status"], "pass", text)

    def test_names_windows_treats_specially(self):
        folder = self.temp / "reserved"
        folder.mkdir()
        self.addCleanup(self.cleanup, folder)
        for name in ("aux.txt", "con", "trailing-dot.", "trailing-space "):
            with open(self.long(folder / "x")[:-1] + name, "wb") as stream:
                stream.write(name.encode() + b"\n")
        out = self.temp / "m.txt"
        code, _, err = run_cli("seal", folder, "--purpose", "p", "--out", out)
        self.assertEqual(code, 0, err)
        text = out.read_bytes()
        self.assertIn(b"  aux.txt\n", text)
        self.assertIn(b"  trailing-dot.\n", text)
        _, result, _ = run_cli("verify", out, "--folder", folder, "--json")
        self.assertEqual(json.loads(result)["files"]["status"], "pass", result)

    def test_a_manifest_inside_a_long_path_folder_leaves_itself_out(self):
        folder = self.write("work/a.txt", b"a\n").parent
        out = folder / "seal.txt"
        self.assertEqual(run_cli("seal", folder, "--purpose", "p", "--out", out)[0], 0)
        _, text, _ = run_cli("verify", out, "--json")
        data = json.loads(text)
        self.assertEqual(data["differences"]["added"], [], text)
        self.assertEqual(data["files"]["status"], "pass", text)


@unittest.skipIf(os.name == "nt", "these names cannot exist on Windows")
class PosixOnlyNames(TempFolderTestCase):
    def test_names_windows_cannot_hold_round_trip_here(self):
        folder = self.temp / "work"
        folder.mkdir()
        for name in ("back\\slash.txt", "co:lon.txt", "new\nline.txt", "tab\tname.txt", "star*.txt", "a?b.txt", '"quoted".txt'):
            (folder / name).write_bytes(name.encode("utf-8") + b"\n")
        out = self.temp / "m.txt"
        code, _, err = run_cli("seal", folder, "--purpose", "p", "--out", out)
        self.assertEqual(code, 0, err)
        self.assertEqual(out.read_bytes().count(b"\n") - 8, 7)
        _, text, _ = run_cli("verify", out, "--folder", folder, "--json")
        self.assertEqual(json.loads(text)["files"]["status"], "pass", text)

    def test_a_name_that_is_not_valid_utf8(self):
        folder = self.temp / "work"
        folder.mkdir()
        with open(os.path.join(os.fsencode(folder), b"latin-caf\xe9.txt"), "wb") as stream:
            stream.write(b"x\n")
        out = self.temp / "m.txt"
        code, printed, err = run_cli("seal", folder, "--purpose", "p", "--out", out)
        self.assertEqual(code, 0, err)
        self.assertIn(b"latin-caf\\xe9.txt\n", out.read_bytes())
        _, text, _ = run_cli("verify", out, "--folder", folder, "--json")
        self.assertEqual(json.loads(text)["files"]["status"], "pass", text)
        code, page, err = run_cli("report", out, "--folder", folder, "--format", "html", "--out", self.temp / "r.html")
        self.assertEqual(code, 3, err)
        code, printed, err = run_cli("seal", folder, "--dry-run", "--out", self.temp / "other.txt")
        self.assertEqual(code, 0, err)
        self.assertIn("\\xe9", printed)
